// Turns android/i18n/<code>.json into the app's string resources.
//
//   node android/scripts/strings.mjs          writes the resources
//   node android/scripts/strings.mjs --check  fails when they are out of date
//
// Placeholders such as {email} become %1$s, numbered in the order of the
// English text, so that every language may place them where it needs.
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sources = join(root, "i18n");
const res = join(root, "app", "src", "main", "res");
const check = process.argv.includes("--check");

/** Android's resource qualifier for each language, old codes included. */
const qualifier = (code) =>
  ({
    en: "values",
    he: "values-iw",
    id: "values-in",
    "pt-BR": "values-pt-rBR",
    "zh-CN": "values-zh-rCN",
    "zh-TW": "values-zh-rTW",
  })[code] ?? `values-${code}`;

const placeholders = (text) => [...text.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
const english = JSON.parse(readFileSync(join(sources, "en.json"), "utf8"));
const order = Object.fromEntries(Object.entries(english).map(([key, text]) => [key, placeholders(text)]));

const escape = (text) =>
  text
    .replace(/\\/g, "\\\\")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/^([@?])/, "\\$1");

let problems = 0;
const fail = (message) => {
  problems++;
  console.error(message);
};

const codes = readdirSync(sources)
  .filter((file) => file.endsWith(".json"))
  .map((file) => file.slice(0, -5))
  .sort();

for (const code of codes) {
  const strings = JSON.parse(readFileSync(join(sources, `${code}.json`), "utf8"));
  const keys = Object.keys(strings);
  if (keys.join() !== Object.keys(english).join()) fail(`${code}: keys differ from en.json`);

  const lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    "<!-- Generated by android/scripts/strings.mjs from android/i18n. Edit the JSON, not this file. -->",
    "<resources>",
  ];
  if (code === "en") lines.push('    <string name="app_name" translatable="false">Snap2Link</string>');
  for (const key of keys) {
    const text = strings[key];
    const names = placeholders(text);
    if ([...names].sort().join() !== [...(order[key] ?? [])].sort().join()) {
      fail(`${code}: ${key} has other placeholders than in English`);
    }
    if (/[–—―]/.test(text)) fail(`${code}: ${key} has a long dash`);
    // A % only needs doubling where the string is formatted.
    const literal = names.length ? escape(text).replace(/%/g, "%%") : escape(text);
    const formatted = literal.replace(/\{(\w+)\}/g, (_, name) => `%${order[key].indexOf(name) + 1}$s`);
    const attributes = names.length > 1 ? ' formatted="true"' : "";
    lines.push(`    <string name="${key.replace(/\./g, "_")}"${attributes}>${formatted}</string>`);
  }
  lines.push("</resources>", "");
  const content = lines.join("\n");

  const dir = join(res, qualifier(code));
  const file = join(dir, "strings.xml");
  if (check) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== content) fail(`${code}: ${file} is out of date`);
  } else {
    mkdirSync(dir, { recursive: true });
    writeFileSync(file, content);
  }
}

// Per-app language setting, Android 13 and later.
const config = [
  '<?xml version="1.0" encoding="utf-8"?>',
  "<!-- Generated by android/scripts/strings.mjs. -->",
  '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">',
  ...codes.map((code) => `    <locale android:name="${code}" />`),
  "</locale-config>",
  "",
].join("\n");
const configFile = join(res, "xml", "locales_config.xml");
if (check) {
  if (!existsSync(configFile) || readFileSync(configFile, "utf8") !== config) fail(`${configFile} is out of date`);
} else {
  mkdirSync(dirname(configFile), { recursive: true });
  writeFileSync(configFile, config);
}

if (problems) process.exit(1);
console.log(check ? `strings up to date (${codes.length} languages)` : `wrote ${codes.length} languages`);
